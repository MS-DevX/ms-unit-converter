  /// Seeds the [collections] table from [predefinedCollections].
  Future<void> _seedCollections(Transaction txn) async {
    var sortOrder = 0;
    for (final col in predefinedCollections) {
      await txn.insert(
        'collections',
        {
          'id': col.id,
          'name': col.name,
          'emoji': col.emoji,
          'description': col.description,
          'display_order': sortOrder++,
          'is_featured': 0,
          'is_hidden': 0,
          'search_weight': 100,
        },
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }
    debugPrint('[DatabaseService]   ↳ ${predefinedCollections.length} collections');
  }

  /// Seeds [collection_items] from [predefinedCollections].
  Future<void> _seedCollectionItems(Transaction txn) async {
    var count = 0;
    for (final col in predefinedCollections) {
      var sortOrder = 0;
      for (final category in col.categories) {
        await txn.insert(
          'collection_items',
          {
            'collection_id': col.id,
            'category_id': category.name,
            'display_order': sortOrder++,
          },
          conflictAlgorithm: ConflictAlgorithm.replace,
        );
        count++;
      }
    }
    debugPrint('[DatabaseService]   ↳ $count collection items');
  }

  /// Seeds the [currencies] table from [allIsoCurrencies].
  Future<void> _seedCurrencies(Transaction txn) async {
    var pinOrder = 0;
    for (final entry in allIsoCurrencies) {
      final isPinned = pinnedCurrencyCodes.contains(entry.code);
      await txn.insert(
        'currencies',
        {
          'iso_code': entry.code,
          'name': entry.name,
          'symbol': entry.symbol,
          'flag': entry.flag,
          'country': entry.country,
          'decimal_digits': entry.decimalDigits,
          'fallback_rate_to_usd': entry.fallbackRateToUsd,
          'is_pinned': isPinned ? 1 : 0,
          'pin_order': isPinned ? pinOrder++ : null,
          'display_order': 0,
          'is_featured': isPinned ? 1 : 0,
          'search_weight': isPinned ? 200 : 100,
        },
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }
    debugPrint('[DatabaseService]   ↳ ${allIsoCurrencies.length} currencies');
  }

  /// Seeds [educational_facts] from [didYouKnowFacts].
  Future<void> _seedEducationalFacts(Transaction txn) async {
    var sortOrder = 0;
    for (final fact in didYouKnowFacts) {
