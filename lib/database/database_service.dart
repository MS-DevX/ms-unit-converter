  /// Seeds the [collections] table from [predefinedCollections].
  Future<void> _seedCollections(Transaction txn) async {
    var sortOrder = 0;
    for (final col in predefinedCollections) {
      await txn.insert(
        'collections',
        {
          'id': col.id,
          'name': col.name,
          'emoji': col.emoji,
          'description': col.description,
          'display_order': sortOrder++,
          'is_featured': 0,
          'is_hidden': 0,
          'search_weight': 100,
        },
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }
    debugPrint('[DatabaseService]   ↳ ${predefinedCollections.length} collections');
  }

  /// Seeds [collection_items] from [predefinedCollections].
  Future<void> _seedCollectionItems(Transaction txn) async {
    var count = 0;
    for (final col in predefinedCollections) {
      var sortOrder = 0;
      for (final category in col.categories) {
        await txn.insert(
          'collection_items',
          {
            'collection_id': col.id,
            'category_id': category.name,
            'display_order': sortOrder++,
          },
          conflictAlgorithm: ConflictAlgorithm.replace,
        );
        count++;
      }
    }
    debugPrint('[DatabaseService]   ↳ $count collection items');
  }

  /// Seeds the [currencies] table from [allIsoCurrencies].
  Future<void> _seedCurrencies(Transaction txn) async {
    var pinOrder = 0;
    for (final entry in allIsoCurrencies) {
      final isPinned = pinnedCurrencyCodes.contains(entry.code);
      await txn.insert(
        'currencies',
        {
          'iso_code': entry.code,
          'name': entry.name,
          'symbol': entry.symbol,
          'flag': entry.flag,
          'country': entry.country,
          'decimal_digits': entry.decimalDigits,
          'fallback_rate_to_usd': entry.fallbackRateToUsd,
          'is_pinned': isPinned ? 1 : 0,
          'pin_order': isPinned ? pinOrder++ : null,
          'display_order': 0,
          'is_featured': isPinned ? 1 : 0,
          'search_weight': isPinned ? 200 : 100,
        },
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
    }
    debugPrint('[DatabaseService]   ↳ ${allIsoCurrencies.length} currencies');
  }

  /// Seeds [educational_facts] from [didYouKnowFacts].
  Future<void> _seedEducationalFacts(Transaction txn) async {
    var sortOrder = 0;
    for (final fact in didYouKnowFacts) {
      await txn.insert(
        'educational_facts',
        {
          'emoji': fact.emoji,
          'fact': fact.fact,
          'category_id': null,
          'display_order': sortOrder++,
          'is_featured': 0,
          'is_hidden': 0,
        },
        conflictAlgorithm: ConflictAlgorithm.replace,
      );
      sortOrder++;
    }
    debugPrint('[DatabaseService]   ↳ ${didYouKnowFacts.length} educational facts');
  }

  /// Seeds [unit_information] from `assets/data/unit_information.json`.
  Future<void> _seedUnitInformation(Transaction txn) async {
    try {
      String? jsonStr;
      try {
        jsonStr = await rootBundle.loadString('assets/data/unit_information.json');
      } catch (_) {
        final file = File('assets/data/unit_information.json');
        if (await file.exists()) {
          jsonStr = await file.readAsString();
        }
      }

      if (jsonStr == null || jsonStr.isEmpty) return;

      final decoded = jsonDecode(jsonStr) as Map<String, dynamic>;
      final unitRows = await txn.query('units', columns: ['id', 'name', 'symbol']);
      final nameToUnit = <String, Map<String, dynamic>>{};
      for (final r in unitRows) {
        nameToUnit[(r['name'] as String).toLowerCase()] = r;
      }

      var count = 0;
      for (final entry in decoded.entries) {
        final key = entry.key.toLowerCase().replaceAll('_', ' ');
        final unitMap = nameToUnit[key] ?? nameToUnit[entry.key.toLowerCase()];
        if (unitMap != null) {
          final unitId = unitMap['id'] as int;
          final symbol = unitMap['symbol'] as String;
          final val = entry.value as Map<String, dynamic>;
          final definition = val['definition'] as String? ?? '';
          final history = val['history'] as String? ?? '';
          final usedFor = val['used_for'] as String? ?? '';
          final examplesList = (val['examples'] as List<dynamic>?)
                  ?.map((e) => e.toString())
                  .toList() ??
              [];

          await txn.insert(
            'unit_information',
            {
              'unit_id': unitId,
              'symbol': val['symbol'] as String? ?? symbol,
              'definition': definition,
              'history': history,
              'used_for': usedFor,
              'examples': jsonEncode(examplesList),
            },
            conflictAlgorithm: ConflictAlgorithm.replace,
          );
          count++;
        }
      }
      debugPrint('[DatabaseService]   ↳ $count unit information records');
    } catch (e) {
      debugPrint('[DatabaseService] Error seeding unit_information: $e');
    }
  }



  /// Closes the database. Should only be called when the app is disposing.
  Future<void> close() async {
    await _db?.close();
    _db = null;
    _initialized = false;
    debugPrint('[DatabaseService] Closed');
  }

  /// Deletes the database file. For development/testing only.
  ///
  /// Call [initialize] again to recreate and reseed.
  @visibleForTesting
  Future<void> deleteDatabase() async {
    await close();
    final dbPath = await _resolveDbPath();
    final file = File(dbPath);
    if (await file.exists()) {
      await file.delete();
      debugPrint('[DatabaseService] Database deleted: $dbPath');
    }
  }
}
