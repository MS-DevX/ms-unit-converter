/// Singleton SQLite database manager for MS Unit Converter.
///
/// Responsibilities:
/// - Open the SQLite database (creating schema on first launch via [MigrationService]).
/// - Check [_contentVersion] against the stored version; reseed from Dart data
///   if the content has changed (new app release with updated data).
/// - Expose a single [Database] instance to all repositories via [database].
///
/// ## Phase 1 Architecture
/// The database is seeded **at runtime** from existing Dart data structures
/// on first launch. This avoids any build-tool or binary-asset dependency.
///
/// ## Phase 2 Architecture (future)
/// The database will be shipped as a pre-built binary asset
/// (`assets/database/unit_converter.db`) generated by `tools/build_database.dart`
/// from JSON content files. `DatabaseService` will copy the asset to the
/// documents directory and open it from there instead of seeding at runtime.
