  /// Seeds [unit_information] from `assets/data/unit_information.json`.
  Future<void> _seedUnitInformation(Transaction txn) async {
    try {
      String? jsonStr;
      try {
        jsonStr = await rootBundle.loadString('assets/data/unit_information.json');
      } catch (_) {
        final file = File('assets/data/unit_information.json');
        if (await file.exists()) {
          jsonStr = await file.readAsString();
        }
      }

      if (jsonStr == null || jsonStr.isEmpty) return;

      final decoded = jsonDecode(jsonStr) as Map<String, dynamic>;
      final unitRows = await txn.query('units', columns: ['id', 'name', 'symbol']);
      final jsonToInfo = <String, Map<String, dynamic>>{};
      for (final entry in decoded.entries) {
        jsonToInfo[entry.key.toLowerCase().replaceAll('_', ' ')] =
            entry.value as Map<String, dynamic>;
        jsonToInfo[entry.key.toLowerCase()] = entry.value as Map<String, dynamic>;
      }

      var count = 0;
